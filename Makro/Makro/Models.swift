            let calls: Int
            let inputTokens: Double
            let outputTokens: Double
        }
        struct WorkflowQuant: Codable, Equatable {
            let prompts: Int
            let inputTokens: Double
            let outputTokens: Double
        }
        let ledger: Quant
        let workflow: WorkflowQuant
        let unattributed: Quant
        let inputRate: Double
    }
    let days: Int
    let tokens: Tokens
    let workflows: Workflows
    let attribution: Attribution?
}

