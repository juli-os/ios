struct Session: Codable, Identifiable, Equatable {
    let name: String
    let active: Bool
    var working: Bool
    var unread: Int
    /// Coding agent holding the pane ("claude", …); empty = bare shell.
    var agent: String
    /// Classified project of the pane's working directory (longest path-prefix
    /// match on the server); empty = unclassified. Drives profile attribution.
    var project: String
    var id: String { name }

    init(name: String, active: Bool, working: Bool = false, unread: Int = 0, agent: String = "", project: String = "") {
        self.name = name
        self.active = active
        self.working = working
        self.unread = unread
        self.agent = agent
        self.project = project
    }

    private enum CodingKeys: String, CodingKey { case name, active, working, unread, agent, project }

    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        name = try c.decode(String.self, forKey: .name)
        active = try c.decode(Bool.self, forKey: .active)
        // working/unread/agent/project are omitempty on the server →
        // decodeIfPresent for backward compatibility with payloads that omit them.
        working = try c.decodeIfPresent(Bool.self, forKey: .working) ?? false
        unread = try c.decodeIfPresent(Int.self, forKey: .unread) ?? 0
        agent = try c.decodeIfPresent(String.self, forKey: .agent) ?? ""
        project = try c.decodeIfPresent(String.self, forKey: .project) ?? ""
    }
}

