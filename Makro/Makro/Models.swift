/// One send-preflight check on a waiting gate: `input.checks[]`.
struct GateCheck: Equatable {
    let name: String
    let status: String // pass | warn | fail
    var detail: String?

    var failed: Bool { status == "fail" }
}

/// Delivery pointer shown on a gate: `deliverables[]` (input or output).
/// `id` addresses the artifact store (fetchable via /api/artifacts/:id/content);
/// view_role "body" marks the email body being approved.
struct GateDeliverable: Equatable {
    let name: String
    var id: String?
    var viewRole: String?
    var summary: String?
    var bytes: Int64?
}

extension LifecycleStep {
    var checkItems: [GateCheck] {
        guard let arr = input?["checks"]?.arrayValue else { return [] }
        return arr.map { v in
            let d = v.dictValue
            return GateCheck(
                name: d?["name"]?.stringValue ?? "?",
                status: d?["status"]?.stringValue ?? "?",
                detail: d?["detail"]?.stringValue
            )
        }
    }

    var hasFailedCheck: Bool { checkItems.contains(where: \.failed) }

    var deliverableItems: [GateDeliverable] {
        let arr = input?["deliverables"]?.arrayValue ?? output?["deliverables"]?.arrayValue ?? []
        return arr.map { v in
            let d = v.dictValue
            var item = GateDeliverable(name: d?["name"]?.stringValue ?? "?", id: nil, viewRole: nil, summary: nil, bytes: nil)
            item.id = d?["id"]?.stringValue
            item.viewRole = d?["view_role"]?.stringValue
            item.summary = d?["summary"]?.stringValue
            if let b = d?["bytes"]?.numberValue { item.bytes = Int64(b) }
            return item
        }
    }

    /// 内联正文（body_source:inline 的邮件稿）。
    var bodyInline: String? {
        guard let b = input?["body"]?.stringValue, !b.isEmpty else { return nil }
        return b
    }

    /// 正文契约路径：body_ref → 工件按 id 取字节、按哈希核验。
    var bodyRef: (id: String, name: String)? {
        guard let d = input?["body_ref"]?.dictValue,
              let id = d["id"]?.stringValue, !id.isEmpty else { return nil }
        return (id, d["name"]?.stringValue ?? "Body")
    }

    /// Server stashes the failure reason on `output.error` (engine.go / capabilities).
    var outputError: String? {
        guard let e = output?["error"]?.stringValue, !e.isEmpty else { return nil }
        return e
    }

    /// The tmux session this step runs in: seeded into agent/verify input by
    /// gate approve; falls back to the workflow's session / assigned_session.
    /// 发送回执（send 步 output：to/sent_at + 随信附件清单）。
    var sendReceipt: (to: String, sentAt: String?, attachments: [String])? {
        guard kind == "send", status == "completed",
              let to = output?["to"]?.stringValue, !to.isEmpty else { return nil }
        let atts = (output?["attachments"]?.arrayValue ?? []).compactMap { a in
            a.dictValue?["name"]?.stringValue ?? a.stringValue
        }
        return (to, output?["sent_at"]?.stringValue, atts)
    }

    /// 无契约 fallback 正文：body_ref/deliverables 都缺席时，正文可能只
    /// 以 output.body / output.draft / output.output 内联存在——审批卡的
    /// 最后防线，保证"点 OK 前看得到内容"永远有东西可看。
    var fallbackBody: String? {
        for key in ["body", "draft", "output"] {
            if let v = output?[key]?.stringValue, v.count > 40 { return v }
        }
        for key in ["body", "draft"] {
            if let v = input?[key]?.stringValue, v.count > 40 { return v }
        }
        return nil
    }

    func sessionName(in workflow: LifecycleWorkflow) -> String? {
        let s = input?["session"]?.stringValue
            ?? workflow.session
            ?? workflow.meta?["assigned_session"]?.stringValue
        return (s?.isEmpty == false) ? s : nil
    }
}

