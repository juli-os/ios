        let byStatus: [WorkflowStatusCount]
    }
    /// 归属率（2026-10-06 web 统计视图替代时新增）：账本全量 vs 单子归属量
    /// （每单 会话×agent 步窗口 的 claude_code 回合）。旧端点缺键 nil。
