// One immutable version in a case's evidence chain (server artifacts table).
struct CaseArtifact: Codable, Identifiable, Equatable {
    let id: String
    let workflow_id: String
    let role: String // intake_attachment | agent_output | draft_attachment
    let name: String
    let seq: Int
    var mime: String?
    let bytes: Int64
    var sha256: String?
    var session: String?
    var storage: ArtifactStorageInfo?
    var created_at: String?
    var deleted_at: String?

    struct ArtifactStorageInfo: Codable, Equatable {
        var backend: String?
    }

    var isPurged: Bool { deleted_at != nil && !(deleted_at ?? "").isEmpty }
    var hasBytes: Bool {
        // "none" backend = identity-only fact (oversize); purged = bytes gone.
        !isPurged && storage?.backend != "none"
    }
    var roleLabel: String {
        switch role {
        case "intake_attachment": return "Inbound attachment"
        case "agent_output": return "Execution output"
        case "draft_attachment": return "Reply attachment"
        case "case_journey": return "Closing flow"
        default: return role
        }
    }
}

/// JSON value wrapper for step input/output maps. Steps stash structured
/// payload here (gate `checks`, `deliverables`, agent `session`, `error`),
/// so the wrapper keeps enough shape to walk one level of nesting.
struct JSONValue: Codable, Equatable {
    let stringValue: String?
    let numberValue: Double?
    let boolValue: Bool?
    let arrayValue: [JSONValue]?
    let dictValue: [String: JSONValue]?

    init(from decoder: Decoder) throws {
        let c = try decoder.singleValueContainer()
        if let s = try? c.decode(String.self) {
            stringValue = s; numberValue = nil; boolValue = nil; arrayValue = nil; dictValue = nil
        } else if let b = try? c.decode(Bool.self) {
            stringValue = nil; numberValue = nil; boolValue = b; arrayValue = nil; dictValue = nil
        } else if let d = try? c.decode(Double.self) {
            stringValue = nil; numberValue = d; boolValue = nil; arrayValue = nil; dictValue = nil
        } else if let a = try? c.decode([JSONValue].self) {
            stringValue = nil; numberValue = nil; boolValue = nil; arrayValue = a; dictValue = nil
        } else if let o = try? c.decode([String: JSONValue].self) {
            stringValue = nil; numberValue = nil; boolValue = nil; arrayValue = nil; dictValue = o
        } else {
            stringValue = nil; numberValue = nil; boolValue = nil; arrayValue = nil; dictValue = nil
        }
    }

    func encode(to encoder: Encoder) throws {
        var c = encoder.singleValueContainer()
        if let v = stringValue { try c.encode(v) }
        else if let v = boolValue { try c.encode(v) }
        else if let v = numberValue { try c.encode(v) }
        else if let v = arrayValue { try c.encode(v) }
        else if let v = dictValue { try c.encode(v) }
        else { try c.encodeNil() }
    }

    init(string: String) {
        stringValue = string; numberValue = nil; boolValue = nil; arrayValue = nil; dictValue = nil
    }

    var isEmpty: Bool {
        stringValue == nil && numberValue == nil && boolValue == nil
            && (arrayValue == nil || arrayValue?.isEmpty == true)
            && (dictValue == nil || dictValue?.isEmpty == true)
    }
}

// MARK: - Gate payload helpers (server shapes: sendChecks.ts / deliverables)

/// One send-preflight check on a waiting gate: `input.checks[]`.
struct GateCheck: Equatable {
    let name: String
    let status: String // pass | warn | fail
    var detail: String?

    var failed: Bool { status == "fail" }
}

/// Delivery pointer shown on a gate: `deliverables[]` (input or output).
/// `id` addresses the artifact store (fetchable via /api/artifacts/:id/content);
/// view_role "body" marks the email body being approved.
struct GateDeliverable: Equatable {
    let name: String
    var id: String?
    var viewRole: String?
    var summary: String?
    var bytes: Int64?
}

extension LifecycleStep {
    var checkItems: [GateCheck] {
        guard let arr = input?["checks"]?.arrayValue else { return [] }
        return arr.map { v in
            let d = v.dictValue
            return GateCheck(
                name: d?["name"]?.stringValue ?? "?",
                status: d?["status"]?.stringValue ?? "?",
                detail: d?["detail"]?.stringValue
            )
        }
    }

    var hasFailedCheck: Bool { checkItems.contains(where: \.failed) }

    var deliverableItems: [GateDeliverable] {
        let arr = input?["deliverables"]?.arrayValue ?? output?["deliverables"]?.arrayValue ?? []
        return arr.map { v in
            let d = v.dictValue
            var item = GateDeliverable(name: d?["name"]?.stringValue ?? "?", id: nil, viewRole: nil, summary: nil, bytes: nil)
            item.id = d?["id"]?.stringValue
            item.viewRole = d?["view_role"]?.stringValue
            item.summary = d?["summary"]?.stringValue
            if let b = d?["bytes"]?.numberValue { item.bytes = Int64(b) }
            return item
        }
    }

    /// Inline body (the email draft for body_source:inline).
    var bodyInline: String? {
        guard let b = input?["body"]?.stringValue, !b.isEmpty else { return nil }
        return b
    }

    /// Body contract path: body_ref → fetch artifact bytes by id, verify by hash.
    var bodyRef: (id: String, name: String)? {
        guard let d = input?["body_ref"]?.dictValue,
              let id = d["id"]?.stringValue, !id.isEmpty else { return nil }
        return (id, d["name"]?.stringValue ?? "Body")
    }

    /// Server stashes the failure reason on `output.error` (engine.go / capabilities).
    var outputError: String? {
        guard let e = output?["error"]?.stringValue, !e.isEmpty else { return nil }
        return e
    }

    /// The tmux session this step runs in: seeded into agent/verify input by
    /// gate approve; falls back to the workflow's session / assigned_session.
    /// Send receipt (send step output: to/sent_at + the attachment list that went along).
    var sendReceipt: (to: String, sentAt: String?, attachments: [String])? {
        guard kind == "send", status == "completed",
              let to = output?["to"]?.stringValue, !to.isEmpty else { return nil }
        let atts = (output?["attachments"]?.arrayValue ?? []).compactMap { a in
            a.dictValue?["name"]?.stringValue ?? a.stringValue
        }
        return (to, output?["sent_at"]?.stringValue, atts)
    }

    /// Contract-less fallback body: when body_ref/deliverables are both
    /// absent, the body may exist only inline in output.body / output.draft /
    /// output.output — the approval card's last line of defense, guaranteeing
    /// there is always something to read before tapping OK.
    var fallbackBody: String? {
        for key in ["body", "draft", "output"] {
            if let v = output?[key]?.stringValue, v.count > 40 { return v }
        }
        for key in ["body", "draft"] {
            if let v = input?[key]?.stringValue, v.count > 40 { return v }
        }
        return nil
    }

    func sessionName(in workflow: LifecycleWorkflow) -> String? {
        let s = input?["session"]?.stringValue
            ?? workflow.session
            ?? workflow.meta?["assigned_session"]?.stringValue
        return (s?.isEmpty == false) ? s : nil
    }
}

