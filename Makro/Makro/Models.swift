struct LifecycleWorkflow: Codable, Identifiable, Equatable {
    let id: String
    let kind: String
    let title: String
    let status: String
    var project: String?
    var session: String?
    let created_at: String
    let updated_at: String
    var prompt_count: Int?
    var waiting_steps: Int?
    /// Per-workflow auto-approve (2026-10-07): true = non-send gates approved automatically (a first-class server-side field).
    var auto_approve: Bool?
    /// Raw workflow meta (assigned_session lives here — the human's routing
    /// decision for the case). Values decode tolerantly: non-strings become
    /// .other so numeric fields (uid) never break the whole workflow decode.
    var meta: [String: WorkflowMetaValue]?
}

enum WorkflowMetaValue: Codable, Equatable {
    case string(String)
    case number(Double)
    case other

    init(from decoder: Decoder) throws {
        let c = try decoder.singleValueContainer()
        if let s = try? c.decode(String.self) {
            self = .string(s)
        } else if let d = try? c.decode(Double.self) {
            self = .number(d)
        } else {
            self = .other
        }
    }

    func encode(to encoder: Encoder) throws {
        var c = encoder.singleValueContainer()
        switch self {
        case .string(let s): try c.encode(s)
        case .number(let d): try c.encode(d)
        case .other: try c.encodeNil()
        }
    }

    var stringValue: String? {
        if case .string(let s) = self { return s }
        return nil
    }

    var intValue: Int? {
        if case .number(let d) = self, d == d.rounded() { return Int(d) }
        return nil
    }
}

struct LifecycleStep: Codable, Identifiable, Equatable {
    let id: String
    let workflow_id: String
    let seq: Int
    let kind: String
    var title: String?
    let status: String
    var input: [String: JSONValue]?
    var output: [String: JSONValue]?
    let updated_at: String
    /// Real node timing data (first moment leaving pending / reaching a
    /// terminal state); the server omits the fields when not yet started.
    /// created_at keeps the old convention (= updated_at) — do not use it as
    /// the start time.
    var started_at: String?
    var completed_at: String?
    var summary: String?

    var isGate: Bool { kind == "gate" }
    var isWaiting: Bool { status == "waiting_human" }
    var displayTitle: String { title ?? kind }

    /// Compact duration: terminal → "Xm"; in flight → "Xm…"; not started → nil.
    var timingLabel: String? {
        guard let start = started_at.flatMap(MakroISO.date(from:)) else { return nil }
        let end = completed_at.flatMap(MakroISO.date(from:)) ?? Date()
        let sec = max(0, Int(end.timeIntervalSince(start)))
        let done = completed_at != nil
        if sec < 60 { return done ? "\(sec)s" : "\(sec)s…" }
        let m = sec / 60
        if m < 60 { return done ? "\(m)m" : "\(m)m…" }
        return done ? "\(m / 60)h\(m % 60)m" : "\(m / 60)h\(m % 60)m…"
    }
}

