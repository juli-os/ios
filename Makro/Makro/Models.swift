// A discoverable artifact (HTML page or video) generated by an AI agent,
// surfaced from the agent's session working directory.
struct Artifact: Codable, Identifiable, Equatable {
    let session: String // owning tmux session (central-store tag)
    let name: String    // basename
    let path: String    // relative to session cwd
    let type: String    // "html" or "video"
    let mtime: Int64    // unix seconds
    let size: Int64     // bytes
    /// Ledger id (server artifacts table) — present for juli store artifacts,
    /// nil for legacy makro central-store files. Required by
    /// POST /api/artifact/share {id}; nil artifacts are not shareable.
    let ledgerId: String?

    // Cross-session uniqueness: two sessions can both have "report.html".
    var id: String { ledgerId ?? "\(session)/\(path)" }
    var isHTML: Bool { type == "html" }
    var isVideo: Bool { type == "video" }

    // Multi-format rich-text viewing (wf_b93d083f6682, 2026-10-05): decided
    // by file extension, not the server-side type (the server files both md
    // and json under text/plain and cannot distinguish them).
    private var lowerName: String { name.lowercased() }
    var isMarkdown: Bool { lowerName.hasSuffix(".md") || lowerName.hasSuffix(".markdown") }
    var isJSON: Bool { lowerName.hasSuffix(".json") }
    var isImage: Bool {
        [".png", ".jpg", ".jpeg", ".gif", ".webp"].contains { lowerName.hasSuffix($0) }
    }
    var isPDF: Bool { lowerName.hasSuffix(".pdf") }
    var isOffice: Bool {
        [".pptx", ".ppt", ".docx", ".doc", ".xlsx", ".xls", ".potx"].contains { lowerName.hasSuffix($0) }
    }
    var isZipLike: Bool { [".zip", ".gz", ".tar", ".7z"].contains { lowerName.hasSuffix($0) } }
    var isTextLike: Bool {
        [".txt", ".log", ".csv", ".yaml", ".yml", ".xml", ".svg", ".plist", ".ini", ".conf"]
            .contains { lowerName.hasSuffix($0) }
    }

    // Owning job (wf_1bc08ecd4184, option A server-side join): data source
    // for the card chip and the preview page's "owning job" banner — legacy
    // makro files lack this key; decodes as nil for tolerance.
    var workflow: ArtifactWorkflowRef? { _workflow }
    private var _workflow: ArtifactWorkflowRef?

    private enum CodingKeys: String, CodingKey {
        case session, name, path, type, mtime, size
        case ledgerId = "id"
        case _workflow = "workflow"
    }

    init(session: String, name: String, path: String, type: String,
         mtime: Int64, size: Int64, ledgerId: String? = nil, workflow: ArtifactWorkflowRef? = nil) {
        self.session = session; self.name = name; self.path = path; self.type = type
        self.mtime = mtime; self.size = size; self.ledgerId = ledgerId
        self._workflow = workflow
    }

    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        session = try c.decode(String.self, forKey: .session)
        name = try c.decode(String.self, forKey: .name)
        path = try c.decode(String.self, forKey: .path)
        type = try c.decode(String.self, forKey: .type)
        mtime = try c.decode(Int64.self, forKey: .mtime)
        size = try c.decode(Int64.self, forKey: .size)
        ledgerId = try c.decodeIfPresent(String.self, forKey: .ledgerId)
        _workflow = try c.decodeIfPresent(ArtifactWorkflowRef.self, forKey: ._workflow)
    }
}

